# Resolve common/plugins.txt + projects/<p>/plugins.txt against the project's
# Jenkins version and write every plugin, dependencies included, with its
# version to projects/<p>/plugins.lock.txt.
#
# Usage: scripts/pin-plugins.sh <project>
##############################################################################
set -euo pipefail

project="${1:?usage: $0 <project>}"
repo="$(cd "$(dirname "$0")/.." && pwd)"
pdir="$repo/projects/$project"
[[ -f "$pdir/project.yaml" ]] || { echo "ERROR: no $pdir/project.yaml" >&2; exit 1; }

version="$(yq -r '.jenkinsVersion' "$pdir/project.yaml")"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cat "$repo/common/plugins.txt" "$pdir/plugins.txt" \
  | sed -e 's/#.*//' -e 's/[[:space:]]//g' | grep -v '^$' | sort -u > "$work/plugins.txt"
chmod -R a+rwX "$work"

echo "Resolving $(wc -l < "$work/plugins.txt") plugins for Jenkins $version"
docker run --rm -v "$work:/work" "jenkins/jenkins:${version}-lts-jdk21" \
  jenkins-plugin-cli --plugin-file /work/plugins.txt \
  --plugin-download-directory /work/dl --list > "$work/out.txt"

{
  echo "# Generated by scripts/pin-plugins.sh for Jenkins $version; do not edit."
  sed -n '/^Resulting plugin list:/,/^$/p' "$work/out.txt" \
    | sed '1d' | awk 'NF==2 {print $1":"$2}' | sort
} > "$pdir/plugins.lock.txt"
echo "Wrote $pdir/plugins.lock.txt ($(($(wc -l < "$pdir/plugins.lock.txt") - 1)) plugins)"
